"""Formal typed interface protocols for the OMNIS CORE subsystem."""

from __future__ import annotations

from typing import Any, Callable, Dict, List, Optional, Protocol, runtime_checkable

from core.schemas import OmnisEvent


@runtime_checkable
class EventBusProtocol(Protocol):
    """Contract for synchronous/event-driven subsystem message buses."""

    def subscribe(self, event_type: str, callback: Callable[[OmnisEvent], None]) -> None: ...
    def publish(self, event: OmnisEvent) -> OmnisEvent: ...
    def emit(self, event_type: str, source: str, payload: Optional[Dict] = None, tick: int = 0) -> OmnisEvent: ...
    def get_counts(self) -> Dict[str, int]: ...


@runtime_checkable
class PersistenceBackendProtocol(Protocol):
    """Contract for OMNIS durable storage backends (SQLite & PostgreSQL)."""

    def save_organism(self, organism_dict: Dict[str, Any], timestamp: str) -> None: ...
    def load_organism(self, organism_id: str) -> Optional[Dict[str, Any]]: ...
    def save_experiment(self, exp: Dict[str, Any]) -> None: ...
    def load_experiments(self, limit: int = 50) -> List[Dict[str, Any]]: ...
    def append_audit_log(self, timestamp: str, actor: str, action: str, details: Dict[str, Any]) -> None: ...
    def close(self) -> None: ...


@runtime_checkable
class OrchestratorProtocol(Protocol):
    """Contract for the central OMNIS orchestration controller."""

    def step(self, steps: int = 1) -> Dict[str, Any]: ...
    def reset(self) -> Dict[str, Any]: ...
    def persist_state(self) -> Dict[str, Any]: ...
    def get_command_centre_status(self) -> Dict[str, Any]: ...
    def shutdown(self) -> None: ...
